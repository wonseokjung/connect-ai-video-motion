// Catalog build: catalog/<source>/<name>/meta.json -> src/catalog/metas.generated.mjs + registry.generated.tsx.
// Project prepare: copies the HyperFrames / Lottie files a plan needs into work/vm-assets/ and writes
// src/catalog/user.generated.tsx so your own .tsx components are bundled with the kit.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {KIT} from './analyze.mjs';
import {validateMeta, kindOf} from '../src/core/catalog.mjs';
import {assetName} from '../src/core/assets.mjs';

const require = createRequire(import.meta.url);
const CAT = path.join(KIT, 'catalog');
const GEN = path.join(KIT, 'src', 'catalog');
const COMPONENT_FILES = ['index.tsx', 'index.jsx'];

export function scanCatalog() {
  const metas = {}, errors = [], dirs = {};
  if (!fs.existsSync(CAT)) return {metas, errors, dirs};
  for (const src of fs.readdirSync(CAT).sort()) {
    const sd = path.join(CAT, src);
    if (!fs.statSync(sd).isDirectory()) continue;
    for (const name of fs.readdirSync(sd).sort()) {
      const d = path.join(sd, name);
      const mf = path.join(d, 'meta.json');
      if (!fs.existsSync(mf)) continue;
      let m;
      try {
        m = JSON.parse(fs.readFileSync(mf, 'utf8'));
      } catch (e) {
        errors.push(`${src}/${name}/meta.json: not valid JSON (${e.message})`);
        continue;
      }
      const errs = validateMeta(m, name);
      const comp = COMPONENT_FILES.find((f) => fs.existsSync(path.join(d, f)));
      const t = m.source?.type;
      if ((t === 'hyperframes' || t === 'lottie') && m.status !== 'needs-download') {
        if (!m.src || !fs.existsSync(path.join(d, m.src))) errs.push(`"src" file ${m.src || '(none)'} is missing`);
      } else if (!comp && m.status !== 'needs-download' && m.status !== 'unsupported') errs.push('index.tsx is missing');
      if (metas[m.kind]) errs.push(`kind "${m.kind}" is used twice`);
      for (const e of errs) errors.push(`${src}/${name}: ${e}`);
      if (errs.length) continue;
      metas[m.kind] = {...m, dir: `catalog/${src}/${name}`, component: comp || null};
      dirs[m.kind] = d;
    }
  }
  return {metas, errors, dirs};
}

export function buildCatalog({log = () => {}} = {}) {
  const {metas, errors} = scanCatalog();
  fs.mkdirSync(GEN, {recursive: true});
  const lines = Object.values(metas).sort((a, b) => (a.kind < b.kind ? -1 : 1));
  const metaJs = `// generated by lib/catalog-build.mjs from catalog/*/*/meta.json. Do not edit; run \`connect-ai-video-motion catalog\`.\nexport const METAS = ${JSON.stringify(Object.fromEntries(lines.map((m) => [m.kind, m])), null, 1)};\n`;
  writeIfChanged(path.join(GEN, 'metas.generated.mjs'), metaJs);
  const imports = [], entries = [];
  lines.forEach((m, i) => {
    if (m.status && m.status !== 'ok') return;
    const t = m.source?.type;
    if (t === 'hyperframes') entries.push(`  ${JSON.stringify(m.kind)}: HyperFramesBlock,`);
    else if (t === 'lottie') entries.push(`  ${JSON.stringify(m.kind)}: LottieFile,`);
    else if (m.component) {
      imports.push(`import C${i} from '../../${m.dir}/${m.component.replace(/\.(tsx|jsx)$/, '')}';`);
      entries.push(`  ${JSON.stringify(m.kind)}: C${i},`);
    }
  });
  const reg = `// generated by lib/catalog-build.mjs. Do not edit; run \`connect-ai-video-motion catalog\`.
import React from 'react';
import {HyperFramesBlock} from '../adapters/HyperFrames';
import {LottieFile} from '../adapters/Lottie';
${imports.join('\n')}

export const REGISTRY: Record<string, React.FC<any>> = {
${entries.join('\n')}
};
`;
  writeIfChanged(path.join(GEN, 'registry.generated.tsx'), reg);
  if (!fs.existsSync(path.join(GEN, 'user.generated.tsx'))) writeUser([]);
  log(`  catalog: ${lines.length} graphics${errors.length ? `, ${errors.length} problem(s)` : ''}`);
  return {metas, errors};
}

// GSAP plugin names a block loads from a CDN (same rule as src/adapters/HyperFrames.tsx gsapPluginsIn)
export function pluginsOf(file) {
  const html = fs.readFileSync(file, 'utf8'), out = [];
  for (const m of html.matchAll(/<script[^>]*src=["'][^"']*gsap[^"']*\/(?:dist\/)?([A-Za-z0-9]+)\.min\.js["']/gi)) if (m[1] !== 'gsap' && !out.includes(m[1])) out.push(m[1]);
  return out;
}

function writeIfChanged(f, text) {
  if (fs.existsSync(f) && fs.readFileSync(f, 'utf8') === text) return;
  fs.writeFileSync(f, text);
}

function writeUser(list) {
  const imports = list.map((x, i) => `import U${i} from ${JSON.stringify(x.abs.replace(/\\/g, '/').replace(/\.(tsx|jsx|ts|js)$/, ''))};`);
  const entries = list.map((x, i) => `  ${JSON.stringify(x.key)}: U${i},`);
  writeIfChanged(
    path.join(GEN, 'user.generated.tsx'),
    `// generated for your project by lib/catalog-build.mjs (your own components from plan.json). Do not edit.\nimport React from 'react';\n${imports.join('\n')}\n\nexport const USER: Record<string, React.FC<any>> = {\n${entries.join('\n')}\n};\n`,
  );
}

/**
 * Get a project ready to render: your own components bundled, HyperFrames / Lottie files copied next to the video.
 * Returns {errors: [sentences], users: [{key, abs}], assets: [names]}.
 */
export function prepareProject(P, plan, metas) {
  const errors = [], users = [], assets = new Set();
  const outDir = path.join(P.work, 'vm-assets');
  fs.mkdirSync(outDir, {recursive: true});
  const copy = (from, name) => {
    const to = path.join(outDir, name);
    if (!fs.existsSync(to) || fs.statSync(to).mtimeMs < fs.statSync(from).mtimeMs || fs.statSync(to).size !== fs.statSync(from).size) fs.copyFileSync(from, to);
    assets.add(name);
  };
  let needsGsap = false;
  const plugins = new Set();
  for (const it of plan.items || []) {
    const kind = kindOf(it.kind);
    const m = metas[kind];
    const id = it.id || kind;
    if (kind === 'custom') {
      if (!it.component) { errors.push(`${id}: kind "custom" needs "component": "./path/To/Thing.tsx"`); continue; }
      const abs = path.resolve(P.dir, it.component);
      if (!fs.existsSync(abs)) { errors.push(`${id}: component ${it.component} not found (looked at ${path.relative(process.cwd(), abs) || abs})`); continue; }
      if (!users.some((u) => u.key === it.component)) users.push({key: it.component, abs});
      continue;
    }
    if (kind === 'hyperframes' || kind === 'lottie') {
      if (!it.src) { errors.push(`${id}: kind "${kind}" needs "src": "./my-file.${kind === 'lottie' ? 'json' : 'html'}"`); continue; }
      const abs = path.resolve(P.dir, it.src);
      if (!fs.existsSync(abs)) { errors.push(`${id}: ${it.src} not found`); continue; }
      copy(abs, assetName(kind, it.src));
      if (kind === 'hyperframes') { needsGsap = true; pluginsOf(abs).forEach((n) => plugins.add(n)); }
      continue;
    }
    if (m && (m.source?.type === 'hyperframes' || m.source?.type === 'lottie') && m.src) {
      copy(path.join(KIT, m.dir, m.src), assetName(kind, m.src));
      if (m.source.type === 'hyperframes') { needsGsap = true; pluginsOf(path.join(KIT, m.dir, m.src)).forEach((n) => plugins.add(n)); }
      for (const extra of m.files || []) copy(path.join(KIT, m.dir, extra), assetName(kind, extra));
    }
  }
  if (needsGsap) {
    // HyperFrames blocks load GSAP from a CDN; we give them the copy that is installed with the kit instead
    try {
      const dist = path.join(path.dirname(require.resolve('gsap/package.json')), 'dist');
      copy(path.join(dist, 'gsap.min.js'), 'gsap.min.js');
      for (const n of plugins) {
        if (fs.existsSync(path.join(dist, n + '.min.js'))) copy(path.join(dist, n + '.min.js'), `gsap-${n}.min.js`);
        else errors.push(`a HyperFrames block loads the GSAP plugin ${n}, which is not in the installed gsap package`);
      }
    } catch {
      errors.push('HyperFrames blocks need the "gsap" package (npm install gsap)');
    }
  }
  writeUser(users);
  return {errors, users, assets: [...assets]};
}
